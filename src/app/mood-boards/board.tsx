import Image from "next/image";
import Link from "next/link";

// Shared layout for the three mood boards: a header, a masonry grid of
// artifacts, and image credits. Each board supplies its own look.

export type Photo = {
  src: string;
  alt: string;
  width: number;
  height: number;
  author: string;
  license: string;
  licenseUrl: string | null;
  source: string;
};

export function Found({ img, className = "" }: { img: Photo; className?: string }) {
  return (
    <Image
      src={img.src}
      alt={img.alt}
      width={img.width}
      height={img.height}
      sizes="(min-width: 1024px) 33vw, (min-width: 640px) 50vw, 100vw"
      className={`w-full ${className}`}
    />
  );
}

export function photoFinder(images: Photo[]) {
  return (name: string) => {
    const img = images.find((i) => i.src.includes(name));
    if (!img) throw new Error(`No mood board image matching "${name}"`);
    return img;
  };
}

export function MoodBoard({
  title,
  tagline,
  mark,
  className,
  titleClassName = "",
  linkClassName = "",
  rule,
  items,
  images,
}: {
  title: string;
  tagline: string;
  mark: string; // color of the ✦ that marks generated artifacts
  className: string; // page background, text color, font
  titleClassName?: string;
  linkClassName?: string;
  rule: string; // color of the line above the credits
  items: React.ReactNode[];
  images: Photo[];
}) {
  return (
    <main className={`min-h-full px-5 py-14 sm:px-12 sm:py-20 lg:px-24 ${className}`}>
      <header className="mx-auto mb-14 flex max-w-7xl flex-wrap items-end justify-between gap-4">
        <div>
          <Link
            href="/"
            className={`text-xs font-bold uppercase tracking-wider underline ${linkClassName}`}
          >
            ← Hub
          </Link>
          <h1 className={`mt-3 text-6xl font-bold leading-none tracking-tighter ${titleClassName}`}>
            {title}
          </h1>
          <p className="mt-2 text-base">{tagline}</p>
        </div>
        <p className="text-xs">
          <span style={{ color: mark }}>✦</span> generated by my agent · {items.length} artifacts
        </p>
      </header>

      <div className="mx-auto max-w-7xl columns-1 gap-8 sm:columns-2 lg:columns-3 [&>*]:mb-8 [&>*]:break-inside-avoid">
        {items.map((item, i) => (
          <div key={i}>{item}</div>
        ))}
      </div>

      <footer
        className="mx-auto mt-20 max-w-7xl border-t pt-4 text-[11px] leading-relaxed"
        style={{ borderColor: rule }}
      >
        <p className="mb-2 font-bold uppercase tracking-wider">Image credits</p>
        <ul className="columns-1 gap-6 sm:columns-2">
          {images.map((img) => (
            <li key={img.src}>
              <a href={img.source} className="underline">
                {img.alt}
              </a>
              {" · "}
              {img.author}
              {" · "}
              {img.licenseUrl ? (
                <a href={img.licenseUrl} className="underline">
                  {img.license}
                </a>
              ) : (
                img.license
              )}
            </li>
          ))}
        </ul>
      </footer>
    </main>
  );
}

export function Generated({ mark, children }: { mark: string; children: React.ReactNode }) {
  return (
    <div className="relative">
      {children}
      <span
        className="absolute right-1.5 top-1 text-xs"
        style={{ color: mark }}
        aria-label="Generated"
      >
        ✦
      </span>
    </div>
  );
}
